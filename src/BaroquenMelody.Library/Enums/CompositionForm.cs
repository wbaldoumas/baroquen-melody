namespace BaroquenMelody.Library.Enums;

/// <summary>
///     The large-scale form a composition takes.
/// </summary>
public enum CompositionForm
{
    /// <summary>
    ///     A fugal exposition whose theme returns through the body and recapitulates before the final cadence.
    /// </summary>
    Fugue,

    /// <summary>
    ///     A ground bass announced alone, then repeated under freshly composed variations - the passacaglia's shape.
    /// </summary>
    GroundBass
}
