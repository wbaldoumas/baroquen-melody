namespace BaroquenMelody.Library.Forms.Enums;

/// <summary>
///     Identifies a ground bass pattern in the built-in bank.
/// </summary>
public enum GroundBass
{
    /// <summary>
    ///     The diatonic descending tetrachord (1-7-6-5), the classic passacaglia and lament frame.
    /// </summary>
    DescendingTetrachord,

    /// <summary>
    ///     The romanesca bass (1-5-6-3-4-1-4-5), familiar from Pachelbel's canon.
    /// </summary>
    Romanesca,

    /// <summary>
    ///     A rounded cadential ground (1-5-3-4-1-6-4-5) in the manner of Purcell's grounds.
    /// </summary>
    CadentialGround
}
